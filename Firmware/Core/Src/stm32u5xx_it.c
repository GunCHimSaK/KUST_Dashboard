/**
  * @brief This function handles Hard fault interrupt.
  */
void HardFault_Handler(void)
{
  /* USER CODE BEGIN HardFault_IRQn 0 */
  /* HardFault = 상태 LED(PC13) 빠른 대칭 점멸 (초당 약 4회)
   *
   * LED 극성은 main.h의 LED_ACTIVE_HIGH를 따라가므로 LED_ON/LED_OFF를 씁니다.
   * (예전 test_nucleo 보드의 상태 LED가 PA5여서 GPIOA PIN5를 직접 때리는
   *  코드가 남아 있었습니다. 이 보드에서 PA5는 SPI1_SCK라, 하드폴트가 나면
   *  LED 대신 LCD 클럭선을 흔들었습니다)
   *
   * GPIO 초기화 전(SystemClock_Config 등)에 폴트가 나도 표시가 되도록
   * GPIOC 클럭과 출력 모드를 여기서 한 번 더 세팅합니다.
   * MX_GPIO_Init()이 이미 돌았다면 같은 값을 다시 쓰는 것뿐이라 무해합니다. */
  __HAL_RCC_GPIOC_CLK_ENABLE();
  {
    uint32_t pos = POSITION_VAL(LED_Pin) * 2U;   /* main.h가 핀을 바꿔도 따라감 */
    MODIFY_REG(LED_GPIO_Port->MODER, (3UL << pos), (1UL << pos));  /* 범용 출력 */
  }
  /* USER CODE END HardFault_IRQn 0 */
  while (1)
  {
    /* USER CODE BEGIN W1_HardFault_IRQn 0 */
    LED_ON();
    for (volatile uint32_t i = 0; i < 5000000; i++) { }  /* ~125ms */
    LED_OFF();
    for (volatile uint32_t i = 0; i < 5000000; i++) { }  /* ~125ms */
    /* USER CODE END W1_HardFault_IRQn 0 */
  }
}

